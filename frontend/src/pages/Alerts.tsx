import { useMutation, useQueryClient } from "@tanstack/react-query";
import { AnimatePresence, motion } from "motion/react";
import { AlertOctagon, BellOff, BellRing, Brain, CheckCheck, CloudRain, Leaf, Send, Trash2, TrendingUp, Users } from "lucide-react";
import { useMemo, useState, type ReactNode } from "react";
import { Link } from "react-router-dom";
import { Badge, Button, Card, CardHeader, EmptyState, ErrorState, LoadingRegion, PageHeader, Skeleton, Tabs } from "../components/ui";
import { del, post } from "../lib/api";
import { SEVERITY_COLORS, SEVERITY_LABEL } from "../lib/aqi";
import { absoluteTime, timeAgo } from "../lib/format";
import { useNotifications, useProfile } from "../lib/queries";
import { useToasts } from "../lib/store";
import type { NotificationItem } from "../lib/types";
import { cn } from "../lib/cn";

const CATEGORY: Record<NotificationItem["category"], { label: string; icon: ReactNode }> = {
  critical: { label: "Critical environmental alert", icon: <AlertOctagon aria-hidden="true" className="h-4 w-4" /> },
  deterioration: { label: "Pollution deterioration", icon: <TrendingUp aria-hidden="true" className="h-4 w-4" /> },
  forecast: { label: "Forecast warning", icon: <CloudRain aria-hidden="true" className="h-4 w-4" /> },
  community: { label: "School & community activity", icon: <Users aria-hidden="true" className="h-4 w-4" /> },
  recommendation: { label: "AI recommendation", icon: <Brain aria-hidden="true" className="h-4 w-4" /> },
  positive: { label: "Positive development", icon: <Leaf aria-hidden="true" className="h-4 w-4" /> },
};
const COOLDOWNS: Record<string, string> = { critical: "2 h", deterioration: "3 h", forecast: "6 h", community: "1 h", recommendation: "12 h", positive: "6 h" };

export default function Alerts() {
  const profile = useProfile();
  const q = useNotifications(profile.isSuccess);
  const qc = useQueryClient();
  const push = useToasts((s) => s.push);
  const [filter, setFilter] = useState<"all" | "unread" | NotificationItem["category"]>("all");
  const refresh = () => void qc.invalidateQueries({ queryKey: ["notifications"] });
  const read = useMutation({ mutationFn: (id: string) => post(`/api/notifications/${id}/read`), onSuccess: refresh });
  const readAll = useMutation({ mutationFn: () => post("/api/notifications/read-all"), onSuccess: refresh });
  const remove = useMutation({ mutationFn: (id: string) => del(`/api/notifications/${id}`), onSuccess: refresh });
  const test = useMutation({
    mutationFn: () => post<NotificationItem>("/api/notifications/test"),
    onSuccess: (n) => {
      refresh();
      push({ title: "Test notification sent", message: `Telegram: ${n.delivery.telegram.replace("_", " ")}`, tone: "success" });
    },
    onError: (e) => push({ title: "Test failed", message: (e as Error).message, tone: "danger" }),
  });

  const items = useMemo(() => {
    const all = q.data?.items ?? [];
    if (filter === "all") return all;
    if (filter === "unread") return all.filter((n) => !n.read);
    return all.filter((n) => n.category === filter);
  }, [q.data, filter]);
  const prefs = profile.data?.notification_prefs;

  return (
    <div>
      <PageHeader
        eyebrow="Notifications & alerts"
        title="Alert centre"
        description="Alerts are generated by background risk detection and filtered for priority, duplicates, cooldowns and your quiet hours."
        actions={
          <>
            <Button variant="outline" size="sm" icon={<Send aria-hidden="true" className="h-3.5 w-3.5" />} loading={test.isPending} onClick={() => test.mutate()}>
              Send test
            </Button>
            <Button variant="ghost" size="sm" icon={<CheckCheck aria-hidden="true" className="h-3.5 w-3.5" />} disabled={!q.data?.unread} onClick={() => readAll.mutate()}>
              Mark all read
            </Button>
          </>
        }
      />
      <div className="grid gap-4 lg:grid-cols-[1fr_320px]">
        <div>
          <div className="mb-3 overflow-x-auto pb-1">
            <Tabs
              label="Filter alerts"
              layoutId="alert-filter"
              value={filter}
              onChange={setFilter}
              tabs={[
                { value: "all", label: "All" },
                { value: "unread", label: `Unread${q.data?.unread ? ` (${q.data.unread})` : ""}` },
                { value: "critical", label: "Critical" },
                { value: "deterioration", label: "Deterioration" },
                { value: "forecast", label: "Forecast" },
                { value: "community", label: "Community" },
                { value: "positive", label: "Positive" },
              ]}
            />
          </div>
          {q.isLoading || profile.isLoading ? (
            <LoadingRegion label="Loading alerts…" className="space-y-2">
              {[0, 1, 2].map((i) => (
                <Skeleton key={i} className="h-24" />
              ))}
            </LoadingRegion>
          ) : q.isError ? (
            <Card hover={false}>
              <ErrorState message={(q.error as Error).message} />
            </Card>
          ) : items.length === 0 ? (
            <Card hover={false}>
              <EmptyState
                icon={<BellOff aria-hidden="true" className="h-5 w-5" />}
                title={filter === "all" ? "No alerts so far" : "Nothing in this view"}
                description="AIRenv only alerts when something changes that matters for you: severe levels, rapid deterioration, forecast warnings or at-risk community activities."
              />
            </Card>
          ) : (
            <ul className="space-y-2">
              <AnimatePresence initial={false}>
                {items.map((n) => {
                  const c = SEVERITY_COLORS[n.severity];
                  return (
                    <motion.li
                      key={n.id}
                      layout
                      initial={{ opacity: 0, x: 24 }}
                      animate={{ opacity: 1, x: 0 }}
                      exit={{ opacity: 0, x: -24, height: 0 }}
                      transition={{ type: "spring", stiffness: 380, damping: 34 }}
                      className={cn("glass relative overflow-hidden rounded-2xl p-4", !n.read && "ring-1 ring-inset")}
                      style={!n.read ? { ["--tw-ring-color" as string]: `${c}40` } : undefined}
                    >
                      <span aria-hidden="true" className="absolute inset-y-0 left-0 w-1" style={{ background: c }} />
                      <div className="flex gap-3">
                        <span aria-hidden="true" className="grid h-9 w-9 shrink-0 place-items-center rounded-xl" style={{ background: `${c}18`, color: c }}>
                          {CATEGORY[n.category]?.icon ?? <BellRing aria-hidden="true" className="h-4 w-4" />}
                        </span>
                        <div className="min-w-0 flex-1">
                          <div className="flex flex-wrap items-center gap-2">
                            <p className="text-sm font-semibold">{n.title}</p>
                            <Badge color={c}>{SEVERITY_LABEL[n.severity]}</Badge>
                            {!n.read && (
                              <span className="inline-flex items-center gap-1 text-[10px] text-cyan">
                                <span aria-hidden="true" className="h-2 w-2 rounded-full bg-cyan" />
                                Unread
                              </span>
                            )}
                          </div>
                          <p className="mt-1 text-xs leading-relaxed text-muted">{n.message}</p>
                          <div className="mt-2 flex flex-wrap items-center gap-x-3 gap-y-1 text-[10px] text-faint">
                            <span>{CATEGORY[n.category]?.label}</span>
                            <span title={absoluteTime(n.created_at)}>{timeAgo(n.created_at)}</span>
                            <span>in-app ✓</span>
                            <span>Telegram: {n.delivery.telegram.replace("_", " ")}</span>
                          </div>
                        </div>
                        <div className="flex shrink-0 flex-col gap-1">
                          {!n.read && (
                            <button type="button" onClick={() => read.mutate(n.id)} className="rounded-lg p-1.5 text-faint hover:bg-white/5 hover:text-ink" aria-label={`Mark as read: ${n.title}`} title="Mark as read">
                              <CheckCheck aria-hidden="true" className="h-4 w-4" />
                            </button>
                          )}
                          <button type="button" onClick={() => remove.mutate(n.id)} className="rounded-lg p-1.5 text-faint hover:bg-white/5 hover:text-red-300" aria-label={`Delete alert: ${n.title}`} title="Delete">
                            <Trash2 aria-hidden="true" className="h-4 w-4" />
                          </button>
                        </div>
                      </div>
                    </motion.li>
                  );
                })}
              </AnimatePresence>
            </ul>
          )}
        </div>

        <div className="space-y-4">
          <Card hover={false}>
            <CardHeader icon={<BellRing aria-hidden="true" className="h-4 w-4" />} title="Your delivery rules" />
            {prefs ? (
              <ul className="space-y-2 text-xs text-muted">
                <li className="flex justify-between"><span>Minimum severity</span><span className="capitalize text-ink">{prefs.min_severity}</span></li>
                <li className="flex justify-between"><span>Quiet hours</span><span className="text-ink">{prefs.quiet_hours.enabled ? `${prefs.quiet_hours.start}–${prefs.quiet_hours.end} (critical still sent)` : "off"}</span></li>
                <li className="flex justify-between"><span>Daily limit (non-critical)</span><span className="text-ink">{prefs.daily_limit}</span></li>
                <li className="flex justify-between"><span>Telegram</span><span className="text-ink">{prefs.telegram ? (profile.data?.telegram ? "on" : "on · not linked") : "off"}</span></li>
              </ul>
            ) : (
              <Skeleton className="h-24" label="Loading delivery rules…" />
            )}
            <Link to="/app/settings" className="mt-3 inline-block text-xs text-cyan hover:underline">
              Change preferences →
            </Link>
          </Card>
          <Card hover={false}>
            <CardHeader title="How AIRenv avoids spam" />
            <ul className="space-y-1.5 text-[11px] leading-relaxed text-muted">
              <li>· Identical alerts are suppressed for 12 hours (deduplication key per signal).</li>
              <li>· Each category has a cooldown; only an escalation in severity breaks it.</li>
              <li>· Severity priority orders the list: critical → high → medium → low.</li>
            </ul>
            <div className="mt-3 grid grid-cols-2 gap-1.5">
              {Object.entries(COOLDOWNS).map(([k, v]) => (
                <div key={k} className="rounded-lg bg-black/15 px-2 py-1.5 text-[10px]">
                  <span className="text-muted">{CATEGORY[k as NotificationItem["category"]].label.split(" ")[0]}</span> <span className="float-right text-ink">{v}</span>
                </div>
              ))}
            </div>
          </Card>
        </div>
      </div>
    </div>
  );
}
