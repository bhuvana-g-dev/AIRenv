import { AnimatePresence } from "motion/react";
import { BellOff, CheckCheck, Send } from "lucide-react";
import { useMemo, useState } from "react";
import { Button, Card, EmptyState, ErrorState, LoadingRegion, PageHeader, Skeleton, Tabs } from "../../components/ui";
import { alertFilterTabs, filterAlerts, type AlertFilter } from "../../lib/alerts";
import { useNotifications, useProfile } from "../../lib/queries";
import { AlertItem } from "./AlertItem";
import { useNotificationActions } from "./hooks";
import { DeliveryRulesCard, SpamRulesCard } from "./SidePanels";

export default function AlertsPage() {
  const profile = useProfile();
  const q = useNotifications(profile.isSuccess);
  const { read, readAll, remove, test } = useNotificationActions();
  const [filter, setFilter] = useState<AlertFilter>("all");
  const items = useMemo(() => filterAlerts(q.data?.items ?? [], filter), [q.data, filter]);

  return (
    <div>
      <PageHeader
        eyebrow="Notifications & alerts"
        title="Alert centre"
        description="Alerts are generated by background risk detection and filtered for priority, duplicates, cooldowns and your quiet hours."
        actions={
          <>
            <Button
              variant="outline"
              size="sm"
              icon={<Send aria-hidden="true" className="h-3.5 w-3.5" />}
              loading={test.isPending}
              onClick={() => test.mutate()}
            >
              Send test
            </Button>
            <Button
              variant="ghost"
              size="sm"
              icon={<CheckCheck aria-hidden="true" className="h-3.5 w-3.5" />}
              disabled={!q.data?.unread}
              onClick={() => readAll.mutate()}
            >
              Mark all read
            </Button>
          </>
        }
      />
      <div className="grid gap-4 lg:grid-cols-[1fr_320px]">
        <div>
          <div className="mb-3 overflow-x-auto pb-1">
            <Tabs
              label="Filter alerts"
              layoutId="alert-filter"
              value={filter}
              onChange={setFilter}
              tabs={alertFilterTabs(q.data?.unread)}
            />
          </div>
          {q.isLoading || profile.isLoading ? (
            <LoadingRegion label="Loading alerts…" className="space-y-2">
              {[0, 1, 2].map((i) => (
                <Skeleton key={i} className="h-24" />
              ))}
            </LoadingRegion>
          ) : q.isError ? (
            <Card hover={false}>
              <ErrorState message={q.error.message} />
            </Card>
          ) : items.length === 0 ? (
            <Card hover={false}>
              <EmptyState
                icon={<BellOff aria-hidden="true" className="h-5 w-5" />}
                title={filter === "all" ? "No alerts so far" : "Nothing in this view"}
                description="AIRenv only alerts when something changes that matters for you: severe levels, rapid deterioration, forecast warnings or at-risk community activities."
              />
            </Card>
          ) : (
            <ul className="space-y-2">
              <AnimatePresence initial={false}>
                {items.map((n) => (
                  <AlertItem key={n.id} n={n} onRead={() => read.mutate(n.id)} onDelete={() => remove.mutate(n.id)} />
                ))}
              </AnimatePresence>
            </ul>
          )}
        </div>
        <div className="space-y-4">
          <DeliveryRulesCard profile={profile.data} />
          <SpamRulesCard />
        </div>
      </div>
    </div>
  );
}
